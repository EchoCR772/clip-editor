const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('trimmer', {
  appName: ipcRenderer.sendSync('app-name'),
  initial: () => ipcRenderer.invoke('initial'),
  pick: () => ipcRenderer.invoke('pick'),
  open: p => ipcRenderer.invoke('open', p),
  closeClip: id => ipcRenderer.invoke('close-clip', id),
  fileSize: p => ipcRenderer.invoke('file-size', p),
  readRange: (p, start, end) => ipcRenderer.invoke('read-range', p, start, end),
  clipboardFile: () => ipcRenderer.invoke('clipboard-file'),
  thumbs: (id, n) => ipcRenderer.invoke('thumbs', id, n),
  waveform: (id, n) => ipcRenderer.invoke('waveform', id, n),
  addAudio: (id, p) => ipcRenderer.invoke('add-audio', id, p),
  removeAudio: (id, p) => ipcRenderer.invoke('remove-audio', id, p),
  export: o => ipcRenderer.invoke('export', o),
  cancel: () => ipcRenderer.invoke('cancel'),
  reveal: p => ipcRenderer.invoke('reveal', p),
  pathFor: file => webUtils.getPathForFile(file),
  onProgress: cb => ipcRenderer.on('progress', (_e, p) => cb(p)),
  onOpen: cb => ipcRenderer.on('open', (_e, info) => cb(info)),
  libScan: () => ipcRenderer.invoke('lib-scan'),
  libThumb: p => ipcRenderer.invoke('lib-thumb', p),
  gameIcon: name => ipcRenderer.invoke('game-icon', name),
  libSaveThumb: (p, dataUrl, duration) => ipcRenderer.invoke('lib-save-thumb', p, dataUrl, duration),
  libAction: (action, p) => ipcRenderer.invoke('lib-action', action, p),
  libTrash: (paths, confirmed) => ipcRenderer.invoke('lib-trash', paths, confirmed),
  libTrashFolders: (dirs, label, confirmed) => ipcRenderer.invoke('lib-trash-folders', dirs, label, confirmed),
  libFolderStats: dirs => ipcRenderer.invoke('lib-folder-stats', dirs),
  libEmptyFolders: () => ipcRenderer.invoke('lib-empty-folders'),
  libTrashEmpty: confirmed => ipcRenderer.invoke('lib-trash-empty', confirmed),
  libAddFolder: () => ipcRenderer.invoke('lib-add-folder'),
  libRemoveFolder: p => ipcRenderer.invoke('lib-remove-folder', p),
  libResetFolders: () => ipcRenderer.invoke('lib-reset-folders'),
  onLibChanged: cb => ipcRenderer.on('lib-changed', () => cb()),
  onLibProgress: cb => ipcRenderer.on('lib-progress', (_e, n) => cb(n)),
  libOpenFolder: p => ipcRenderer.invoke('lib-open-folder', p),
  qtOpen: p => ipcRenderer.invoke('qt-open', p),
  qtClose: p => ipcRenderer.invoke('qt-close', p),
  qtWave: (p, dur, buckets) => ipcRenderer.invoke('qt-wave', p, dur, buckets),
  qtEdit: (p, e) => ipcRenderer.invoke('qt-edit', p, e),
  qtExport: o => ipcRenderer.invoke('qt-export', o),
  qtPrepare: o => ipcRenderer.invoke('qt-prepare', o),
  qtEncoder: () => ipcRenderer.invoke('qt-encoder'),
  copyFiles: list => ipcRenderer.invoke('copy-files', list),
  onQtProgress: cb => ipcRenderer.on('qt-progress', (_e, p) => cb(p)),
  settingsGet: () => ipcRenderer.invoke('settings-get'),
  oldTrims: () => ipcRenderer.invoke('old-trims'),
  moveOldTrims: () => ipcRenderer.invoke('move-old-trims'),
  exportPickDir: () => ipcRenderer.invoke('export-pick-dir'),
  exportOpenDir: () => ipcRenderer.invoke('export-open-dir'),
  settingsSet: patch => ipcRenderer.invoke('settings-set', patch),
  thumbsClear: () => ipcRenderer.invoke('thumbs-clear'),
  onNav: cb => ipcRenderer.on('nav', (_e, dir) => cb(dir)),
  selftestConfig: () => ipcRenderer.invoke('selftest-config'),
  selftestDone: r => ipcRenderer.invoke('selftest-done', r),
});
